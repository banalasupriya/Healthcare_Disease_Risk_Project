def create_assessment(patient, recipient, model, cohort, fasting_glucose, smtp_password):
    model_input = pd.DataFrame([patient])
    probability = float(model.predict_proba(model_input)[0, 1])
    category = "Low" if probability <= 0.33 else "Medium" if probability <= 0.66 else "High"
    prediction = "Positive" if probability >= 0.50 else "Negative"
    glucose_level = glucose_category(fasting_glucose)
    assessment_id = (
        f"P-{datetime.now().strftime('%Y%m%d-%H%M%S')}-{uuid.uuid4().hex[:8].upper()}"
    )
    result = {
        "patient_id": assessment_id, **patient, "target": pd.NA,
        "risk_probability": probability, "risk_category": category,
        "prediction": prediction, "record_type": "New assessment",
        "evaluation_partition": "New assessment (unlabeled)",
        "fasting_glucose_mg_dl": fasting_glucose if fasting_glucose is not None else pd.NA,
        "glucose_reference_level": glucose_level,
        "diabetes_level": glucose_level,
    }
    OUTPUT_DIR.mkdir(exist_ok=True)
    result_frame = pd.DataFrame([result])
    result_frame.to_csv(OUTPUT_DIR / "prediction_result.csv", index=False)
    export_columns = list(cohort.columns)
    for column in ("fasting_glucose_mg_dl", "glucose_reference_level", "diabetes_level"):
        if column not in export_columns:
            export_columns.append(column)
    combined = pd.concat(
        [cohort.reindex(columns=export_columns), result_frame.reindex(columns=export_columns)],
        ignore_index=True,
    )
    combined.to_csv(OUTPUT_DIR / "dashboard_data.csv", index=False)
    report_path = create_report(
        patient, prediction, assessment_id, fasting_glucose, glucose_level,
    )
    pdf_path = create_pdf_report(patient, prediction, assessment_id, fasting_glucose, glucose_level)
    if not smtp_password:
        email_status = "Report created, but email was not sent because the Gmail app password was blank."
    else:
        try:
            send_result_email(
                recipient, prediction, probability, assessment_id, smtp_password,
                fasting_glucose, glucose_level, pdf_path,
            )
            email_status = "Email with PDF attachment sent successfully through Gmail SMTP."
        except (OSError, ValueError, smtplib.SMTPException) as error:
            email_status = f"Report created, but email could not be sent: {html.escape(str(error))}"
    report = report_path.read_text(encoding="utf-8")
    status = f'<p class="notice">{email_status}</p>'
    return report.replace("</main>", f"{status}<p>Recipient: {html.escape(recipient)}</p></main>")


def main():
    if not MODEL_FILE.exists():
        raise FileNotFoundError(
            f"Saved model not found at {MODEL_FILE}. Run run_project.py first."
        )
    if not POWER_BI_FILE.exists():
        raise FileNotFoundError(
            f"Power BI dataset not found at {POWER_BI_FILE}. Run model training first."
        )

    model = joblib.load(MODEL_FILE)
    cohort = pd.read_csv(POWER_BI_FILE)
    smtp_password = os.environ.get("SMTP_PASSWORD")
    if not smtp_password:
        smtp_password = getpass("Gmail app password (input hidden): ")
    smtp_password = "".join(smtp_password.split())
    age_min = int(pd.to_numeric(cohort["age"], errors="coerce").min())
    age_max = int(pd.to_numeric(cohort["age"], errors="coerce").max())
    class AssessmentHandler(BaseHTTPRequestHandler):
        def do_GET(self):
            if self.path != "/":
                self.send_error(404)
                return
            body = render_form(age_min, age_max).encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def do_POST(self):
            if self.path != "/assess":
                self.send_error(404)
                return
            try:
                length = int(self.headers.get("Content-Length", "0"))
                values = parse_qs(self.rfile.read(length).decode("utf-8"), strict_parsing=True)
                age = int(values["age"][0])
                gender = values["gender"][0]
                recipient = values["recipient"][0].strip()
                glucose_text = values.get("fasting_glucose", [""])[0].strip()
                fasting_glucose = None if not glucose_text else float(glucose_text)
                if not age_min <= age <= age_max or gender not in {"male", "female"} or "@" not in recipient:
                    raise ValueError("Check the age, gender, and recipient email fields.")
                if fasting_glucose is not None and not 0 <= fasting_glucose <= 1000:
                    raise ValueError("Enter fasting glucose from 0 to 1000 mg/dL, or leave it blank.")
                patient = {"age": age, "gender": gender}
                for column in SYMPTOM_COLUMNS:
                    answer = values[column][0]
                    if answer not in {"yes", "no"}:
                        raise ValueError("Choose Yes or No for every questionnaire item.")
                    patient[column] = answer
                page = create_assessment(
                    patient, recipient, model, cohort, fasting_glucose, smtp_password
                ).encode("utf-8")
                self.send_response(200)
                self.send_header("Content-Type", "text/html; charset=utf-8")
                self.send_header("Content-Length", str(len(page)))
                self.end_headers()
                self.wfile.write(page)
            except (KeyError, ValueError, UnicodeDecodeError) as error:
                body = f"<h1>Form error</h1><p>{html.escape(str(error))}</p><a href='/'>Return to form</a>".encode("utf-8")
                self.send_response(400)
                self.send_header("Content-Type", "text/html; charset=utf-8")
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)
            except Exception as error:
                print(f"[assessment form] Request failed: {error!r}")
                body = (
                    "<h1>Could not create the report</h1>"
                    "<p>The server encountered an error. Check the terminal running the app for details, "
                    "then restart the app and try again.</p><a href='/'>Return to form</a>"
                ).encode("utf-8")
                try:
                    self.send_response(500)
                    self.send_header("Content-Type", "text/html; charset=utf-8")
                    self.send_header("Content-Length", str(len(body)))
                    self.end_headers()
                    self.wfile.write(body)
                except (BrokenPipeError, ConnectionResetError):
                    pass

        def log_message(self, format_string, *args):
            print("[assessment form] " + format_string % args)

    server = HTTPServer(("127.0.0.1", 0), AssessmentHandler)
    url = f"http://127.0.0.1:{server.server_port}"
    print(f"\nAssessment form ready: {url}")
    print("Fill in the browser form, including the recipient email. Stop the server with Ctrl+C when finished.")
    webbrowser.open(url, new=2)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nAssessment form stopped.")
    finally:
        server.server_close()


if __name__ == "__main__":
    main()

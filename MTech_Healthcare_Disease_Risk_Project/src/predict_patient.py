def send_result_email(recipient, prediction, probability, assessment_id, smtp_password,
                      fasting_glucose, glucose_level, pdf_path):
    """Send a result email using Gmail SMTP with STARTTLS."""
    if prediction == "Negative":
        subject = "Questionnaire assessment: follow-up recommended"
        message = (
            "The questionnaire model returned a Negative result. This is not a diagnosis, "
            "and a negative result cannot rule out diabetes. If you have symptoms or concerns, "
            "please seek assessment from a qualified healthcare professional."
        )
    else:
        subject = "Questionnaire assessment result"
        message = (
            "The questionnaire model returned a Positive result. This is not a diagnosis. "
            "Please discuss the result with a qualified healthcare professional for proper evaluation."
        )
    mail = EmailMessage()
    mail["Subject"] = subject
    mail["From"] = SMTP_USER
    mail["To"] = recipient
    glucose_value = "Not provided" if fasting_glucose is None else f"{fasting_glucose:g} mg/dL"
    mail.set_content(
        f"{message}\n\nDiabetes Points: {glucose_value}\n"
        f"Diabetes Level: {glucose_level}\nPatient ID: {assessment_id}\n"
        "The patient profile is attached as a PDF."
    )
    mail.add_attachment(
        pdf_path.read_bytes(), maintype="application", subtype="pdf",
        filename=f"Patient_Diabetes_History_Profile_{assessment_id}.pdf",
    )
    context = ssl.create_default_context()
    with smtplib.SMTP(SMTP_HOST, SMTP_PORT, timeout=20) as server:
        server.starttls(context=context)
        server.login(SMTP_USER, smtp_password)
        server.send_message(mail)
    return True


